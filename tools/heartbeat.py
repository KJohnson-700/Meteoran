"""HEARTBEAT -- one markdown brief for Hermes, written to the vault. Read-only.

Answers, in order, the only questions that matter between check-ins:
  1. is the operator's money still in range, and what is it worth
  2. are the background watchers actually alive (a dead poller is silent, not safe)
  3. is there a pool worth entering, and is it NEW or a repeat (rule 27)

Writes  ~/Documents/Hermes Second Brain/cron/YYYY-MM-DD-HHMMZ-meteoran-heartbeat.md
and pushes to the phone ONLY when something needs a decision -- never on a quiet tick.

    python3 tools/heartbeat.py [wallet]     # wallet defaults to data/operator_wallet.txt
"""
import json, os, subprocess, sys, time, urllib.request, importlib.util

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VAULT = os.path.expanduser("~/Documents/Hermes Second Brain/cron")
API = "https://dlmm.datapi.meteora.ag"


def load(name, path):
    s = importlib.util.spec_from_file_location(name, os.path.join(ROOT, "tools", path))
    m = importlib.util.module_from_spec(s); s.loader.exec_module(m); return m


def alive(pat):
    try:
        out = subprocess.run(["pgrep", "-f", pat], capture_output=True, text=True, timeout=10)
        return bool(out.stdout.strip())
    except Exception:
        return False


def main():
    sys.argv = [sys.argv[0]]                       # tool modules parse argv on import
    mp, pa, nt = load("mp", "monitor_positions.py"), load("pa", "pool_alert.py"), load("nt", "notify.py")

    wf = os.path.join(ROOT, "data", "operator_wallet.txt")
    w = (sys.argv[1] if len(sys.argv) > 1 else
         (open(wf).read().strip() if os.path.exists(wf) else None))

    now = time.gmtime()
    L, urgent = [], []
    L.append(f"# Meteoran heartbeat — {time.strftime('%Y-%m-%d %H:%M UTC', now)}\n")

    # --- 1. the operator's own money -------------------------------------------------
    L.append("## Open positions\n")
    if not w:
        L.append("No wallet on file (`data/operator_wallet.txt`). Cannot see his book.\n")
    else:
        b = mp.book(w)
        if b is None:
            L.append("**POLL FAILED** — state unknown. Not the same as 'no positions'.\n")
        elif not b:
            L.append("Nothing open. Capital is idle.\n")
        else:
            dep = sum(v["dep"] for v in b.values()); pnl = sum(v["pnl"] for v in b.values())
            L.append(f"| pool | size | mark | in range |\n|---|---|---|---|")
            for a, v in sorted(b.items(), key=lambda kv: kv[1]["pnl"]):
                rng = "**OUT — DOWNSIDE**" if v["oor"] else "yes"
                L.append(f"| {mp.name(a)} | {v['dep']:.3f} SOL | {v['pct']:+.2f}% | {rng} |")
                if v["oor"]:
                    urgent.append(f"{mp.name(a)} OUT OF RANGE at {v['pct']:+.1f}%")
            L.append(f"\n{dep:.3f} SOL deployed, {pnl:+.4f} SOL ({100*pnl/max(dep,1e-9):+.2f}%)\n")
            L.append("> Exit rule: out of range on the DOWNSIDE means close. 21,165 measured\n"
                     "> positions ended below their floor and only **20%** finished green.\n")

    # --- 2. are the watchers actually running ----------------------------------------
    L.append("\n## Watchers\n")
    for pat, what in (("pool_alert.py", "pool scanner"), ("monitor_positions.py", "position monitor")):
        ok = alive(pat)
        L.append(f"- {what}: {'**alive**' if ok else '**DEAD — restart it**'}")
        if not ok: urgent.append(f"{what} is DEAD")

    # --- 3. is there anything worth entering -----------------------------------------
    L.append("\n## Pool candidates\n")
    c = pa.candidates(7.0, 20_000)
    if c is None:
        L.append("Scan FAILED. Not the same as 'nothing qualifies'.\n")
    elif not c:
        L.append("Nothing clears the gates. That is a normal state — **do not loosen the\n"
                 "gates to manufacture a candidate** (rule 27).\n")
    else:
        seen_p = os.path.join(ROOT, "data", "pool_alert_seen.json")
        seen = json.load(open(seen_p)) if os.path.exists(seen_p) else {}
        c.sort(key=lambda r: -r["rate"])
        L.append("| pool | rate now | trend | off high | 24h | TVL | holders | first seen |\n"
                 "|---|---|---|---|---|---|---|---|")
        for r in c[:6]:
            ts = seen.get(r["addr"])
            age = "**NEW**" if not ts else time.strftime("%m-%d %H:%MZ", time.gmtime(ts))
            L.append(f"| {r['name']} | {r['rate']:.1f}%/day | {r['trend']:.2f}x | {r['off']:.1f}% | "
                     f"{r['mv']:+.1f}% | ${r['tvl']:,.0f} | {r['holders']:,} | {age} |")
        L.append("\n> A row whose 'first seen' is not NEW is a REPEAT. Say so out loud —\n"
                 "> never re-present an old call as a discovery (rule 27).\n")

    L.append("\n---\nGenerated by `tools/heartbeat.py`. Read-only: no keys, places nothing.\n"
             "Methodology: `~/Documents/Hermes Second Brain/projects/meteoran/`\n")

    os.makedirs(VAULT, exist_ok=True)
    path = os.path.join(VAULT, time.strftime("%Y-%m-%d-%H%MZ-meteoran-heartbeat.md", now))
    tmp = path + ".tmp"
    with open(tmp, "w") as fh: fh.write("\n".join(L))
    os.replace(tmp, path)
    print(path)

    # push only when a human decision is actually required
    if urgent:
        nt.push("Meteoran needs you", " · ".join(urgent[:3]), "urgent", "rotating_light")


if __name__ == "__main__":
    main()
